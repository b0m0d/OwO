# ------------------------------------------------------------------ 基础工具
def ptext(p):
    return p.text.strip()


def find_p(prefix, start=0):
    hits = [p for p in doc.paragraphs if ptext(p).startswith(prefix)]
    assert len(hits) == 1, (prefix, len(hits))
    return hits[0]


def write_p(p, text):
    runs = p.runs
    if runs:
        runs[0].text = text
        for r in runs[1:]:
            r.text = ""
    else:
        p.add_run(text)


def insert_after(ref, text):
    new_el = copy.deepcopy(ref._element)
    ref._element.addnext(new_el)
    p = Paragraph(new_el, doc)
    write_p(p, text)
    return p


def insert_before(ref, text):
    new_el = copy.deepcopy(ref._element)
    ref._element.addprevious(new_el)
    p = Paragraph(new_el, doc)
    write_p(p, text)
    return p


def delete_p(p):
    p._element.getparent().remove(p._element)


def para_after_el(el, text):
    """在任意 XML 元素之后插入一个正文段落（版式沿用正文模板）。"""
    new_el = copy.deepcopy(TEMPLATE_P._element)
    el.addnext(new_el)
    p = Paragraph(new_el, doc)
    write_p(p, text)
    return p


def caption_map():
    cur, m = None, {}
    for el in body.iterchildren():
        if el.tag.endswith('}p'):
            t = ''.join(n.text or '' for n in el.iter(qn('w:t'))).strip()
            if t.startswith('表 '):
                cur = t
        elif el.tag.endswith('}tbl'):
            if cur:
                m[cur] = el
                cur = None
    return m


def tbl_el(header_prefix):
    """按表头文字定位表格元素。"""
    for el in body.iterchildren():
        if el.tag.endswith('}tbl'):
            t = Table(el, doc)
            hdr = "".join(c.text for c in t.rows[0].cells)
            if hdr.startswith(header_prefix):
                return el
    raise KeyError(header_prefix)


def set_cell_text(cell, text):
    while len(cell._tc.findall(qn('w:p'))) > 1:
        cell._tc.remove(cell._tc.findall(qn('w:p'))[-1])
    p = cell.paragraphs[0]
    if p.runs:
        p.runs[0].text = text
        for r in p.runs[1:]:
            r.text = ""
    else:
        p.add_run(text)


def rebuild(header_prefix, rows):
    el = tbl_el(header_prefix)
    ncols = len(rows[0])
    trs = el.findall(qn('w:tr'))
    while len(trs) < len(rows):
        new_tr = copy.deepcopy(trs[-1])
        trs[-1].addnext(new_tr)
        trs = el.findall(qn('w:tr'))
    while len(trs) > len(rows):
        trs[-1].getparent().remove(trs[-1])
        trs = el.findall(qn('w:tr'))
    for tr in trs:
        tcs = tr.findall(qn('w:tc'))
        while len(tcs) < ncols:
            new_tc = copy.deepcopy(tcs[-1])
            tcs[-1].addnext(new_tc)
            tcs = tr.findall(qn('w:tc'))
        while len(tcs) > ncols:
            tcs[-1].getparent().remove(tcs[-1])
            tcs = tr.findall(qn('w:tc'))
    grid = el.find(qn('w:tblGrid'))
    for gc in grid.findall(qn('w:gridCol')):
        grid.remove(gc)
    per = int(round(9639 / ncols))
    for _ in range(ncols):
        grid.append(grid.makeelement(qn('w:gridCol'), {qn('w:w'): str(per)}))
    t = Table(el, doc)
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            set_cell_text(t.rows[ri].cells[ci], val)
        for tc in trs[ri].findall(qn('w:tc')):
            tcpr = tc.find(qn('w:tcPr'))
            if tcpr is None:
                continue
            tcw = tcpr.find(qn('w:tcW'))
            if tcw is not None:
                tcw.set(qn('w:w'), str(per))
                tcw.set(qn('w:type'), 'dxa')


def delete_table(header_prefix):
    el = tbl_el(header_prefix)
    el.getparent().remove(el)


def insert_table_after(ref_p, rows, template_header):
    new_el = copy.deepcopy(tbl_el(template_header))
    ref_p._element.addnext(new_el)
    rebuild(rows[0][0] if False else "".join(rows[0]), rows) if False else None
    return new_el


