# ------------------------------------------------------------------ 基础工具
def ptext(p):
    return p.text.strip()


def para_by_text(text, nth=0):
    hits = [p for p in doc.paragraphs if ptext(p) == text]
    if len(hits) <= nth:
        raise KeyError("paragraph not found: %r (hits=%d)" % (text, len(hits)))
    return hits[nth]


def write_para(p, text):
    runs = p.runs
    if runs:
        runs[0].text = text
        for r in runs[1:]:
            r.text = ""
    else:
        p.add_run(text)


def replace_prefix(prefix, new_text):
    hits = [p for p in doc.paragraphs if ptext(p).startswith(prefix)]
    if len(hits) != 1:
        raise KeyError("expect 1 hit for %r, got %d" % (prefix, len(hits)))
    write_para(hits[0], new_text)


def clone_para_after(ref, text):
    new_el = copy.deepcopy(ref._element)
    ref._element.addnext(new_el)
    p = Paragraph(new_el, doc)
    write_para(p, text)
    return p


def para_tag(text):
    """构造一个普通正文段落元素（版式沿用正文段落）。"""
    el = copy.deepcopy(TEMPLATE_BODY._element if TEMPLATE_BODY is not None else doc.paragraphs[0]._element)
    p = Paragraph(el, doc)
    write_para(p, text)
    return el


def para_after(el, text):
    """在 XML 元素之后插入新段落。"""
    new_el = para_tag(text)
    el.addnext(new_el)
    return Paragraph(new_el, doc)


def set_cell_text(cell, text):
    while len(cell._tc.findall(qn('w:p'))) > 1:
        cell._tc.remove(cell._tc.findall(qn('w:p'))[-1])
    p = cell.paragraphs[0]
    if p.runs:
        p.runs[0].text = text
        for r in p.runs[1:]:
            r.text = ""
    else:
        p.add_run(text)


def caption_map():
    cur = None
    m = {}
    for el in body.iterchildren():
        if el.tag.endswith('}p'):
            txt = ''.join(n.text or '' for n in el.iter(qn('w:t'))).strip()
            if txt.startswith('表 '):
                cur = txt
        elif el.tag.endswith('}tbl'):
            if cur:
                m[cur] = el
                cur = None
    return m


CAPS = caption_map()
TEMPLATE_BODY = [p for p in doc.paragraphs if p.style.name == 'Normal' and p.runs
                 and p.runs[0].font.size and p.runs[0].font.size.pt == 10.5][0]


def cap_el(prefix):
    for cap, el in CAPS.items():
        if cap.startswith(prefix):
            return el, cap
    raise KeyError("caption not found: " + prefix)


def tbl(prefix):
    el, _ = cap_el(prefix)
    return Table(el, doc)


def set_cell(prefix, row, col, text):
    set_cell_text(tbl(prefix).rows[row].cells[col], text)


def rebuild_el(el, rows):
    ncols = len(rows[0])
    trs = el.findall(qn('w:tr'))
    while len(trs) < len(rows):
        new_tr = copy.deepcopy(trs[-1])
        trs[-1].addnext(new_tr)
        trs = el.findall(qn('w:tr'))
    while len(trs) > len(rows):
        trs[-1].getparent().remove(trs[-1])
        trs = el.findall(qn('w:tr'))
    for tr in trs:
        tcs = tr.findall(qn('w:tc'))
        while len(tcs) < ncols:
            new_tc = copy.deepcopy(tcs[-1])
            tcs[-1].addnext(new_tc)
            tcs = tr.findall(qn('w:tc'))
        while len(tcs) > ncols:
            tcs[-1].getparent().remove(tcs[-1])
            tcs = tr.findall(qn('w:tc'))
    grid = el.find(qn('w:tblGrid'))
    for gc in grid.findall(qn('w:gridCol')):
        grid.remove(gc)
    per = int(round(9639 / ncols))
    for _ in range(ncols):
        grid.append(grid.makeelement(qn('w:gridCol'), {qn('w:w'): str(per)}))
    t = Table(el, doc)
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            set_cell_text(t.rows[ri].cells[ci], val)
        for tc in trs[ri].findall(qn('w:tc')):
            tcpr = tc.find(qn('w:tcPr'))
            if tcpr is None:
                continue
            tcw = tcpr.find(qn('w:tcW'))
            if tcw is not None:
                tcw.set(qn('w:w'), str(per))
                tcw.set(qn('w:type'), 'dxa')
    return el


def rebuild(prefix, rows):
    el, _ = cap_el(prefix)
    return rebuild_el(el, rows)


